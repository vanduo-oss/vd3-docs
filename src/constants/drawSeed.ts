/** Target inset as a fraction of the shorter canvas edge (~50% artwork fill). */
export const DRAW_DEMO_FIT_INSET = 0.25;

export function fitDrawDemoView(
  instance:
    | {
        fitView?: (padding?: number) => void;
        canvasEl?: { getBoundingClientRect?: () => DOMRect };
      }
    | null
    | undefined,
) {
  if (!instance?.fitView) return;
  const rect = instance.canvasEl?.getBoundingClientRect?.();
  const pad =
    rect?.width && rect?.height
      ? Math.round(Math.min(rect.width, rect.height) * DRAW_DEMO_FIT_INSET)
      : 96;
  instance.fitView(pad);
}

